test('contributor creates, edits and deactivates an offer',async({page})=>{
 await page.goto('/login');
 await page.getByRole('button',{name:/CSR contributor/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.goto('/offers');
 await page.getByRole('button',{name:'Create offer',exact:true}).click();
 await page.getByLabel('Resource category',{exact:true}).selectOption('Other');
 await page.getByLabel('Total capacity',{exact:true}).fill('3');
 await page.getByLabel('Unit',{exact:true}).fill('boxes');
 const tag='browser-offer-'+Date.now();
 await page.getByLabel('Skills / specifications (comma separated)').fill(tag);
 await page.getByRole('button',{name:'Save offer'}).click();
 const card=page.locator('.offer-card').filter({hasText:tag});
 await expect(card).toContainText('3boxes available');
 await card.getByRole('button',{name:'Edit offer'}).click();
 await page.getByLabel('Total capacity',{exact:true}).fill('5');
 await page.getByRole('button',{name:'Save offer'}).click();
 await expect(card).toContainText('5boxes available');
 await card.getByRole('button',{name:'Deactivate',exact:true}).click();
 await expect(card.locator('.badge')).toHaveText('inactive');
});

test('NGO creates multiple needs and administrator reviews a profile',async({page})=>{
 await page.goto('/login');
 await page.getByRole('button',{name:/NGO organizer/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.goto('/projects/new');
 const title='Browser multiple needs '+Date.now();
 await page.getByLabel('Project title',{exact:true}).fill(title);
 await page.getByLabel('Description',{exact:true}).fill('A functional test of a project with two different resource requirements.');
 await page.getByRole('button',{name:'Add requirement'}).click();
 await expect(page.getByLabel('Resource category',{exact:true})).toHaveCount(2);
 await page.getByLabel('Resource category',{exact:true}).nth(1).selectOption('Funding');
 await page.getByLabel('Unit',{exact:true}).nth(1).fill('INR');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(page.getByRole('heading',{name:title})).toBeVisible();
 await expect(page.locator('tbody tr')).toHaveCount(2);
 await page.goto('/login');
 await page.getByRole('button',{name:/Demo administrator/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.goto('/admin');
 const review=page.getByRole('combobox',{name:'Verification for Udaan Learning Collective · Demo'});
 const initial=await review.inputValue();
 await review.selectOption(initial==='verified'?'pending':'verified');
 await expect(page.getByRole('status')).toContainText('Verification review recorded.');
 await review.selectOption(initial);
 await expect(review).toHaveValue(initial);
});
