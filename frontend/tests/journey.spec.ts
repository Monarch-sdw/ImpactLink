import {test,expect} from '@playwright/test';
test('judge journey: proposed funding becomes committed and delivered',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/login');
 await page.getByRole('button',{name:/NGO organizer/}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.getByRole('link',{name:'Create new project'}).click();
 await page.getByLabel('Project title',{exact:true}).fill('Browser journey '+Date.now());
 await page.getByLabel('Description',{exact:true}).fill('A browser-tested community programme requiring funding and volunteer support.');
 await page.getByLabel('Resource category',{exact:true}).selectOption('Funding');
 await page.getByLabel('Quantity',{exact:true}).fill('100');
 await page.getByLabel('Unit',{exact:true}).fill('INR');
 await page.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(page.getByRole('heading',{name:/Browser journey/})).toBeVisible();
 await page.getByRole('button',{name:'Find matching partners',exact:true}).click();
 const card=page.locator('.match-card').first();
 await expect(card).toContainText('Proposed: 100 INR');
 const organization=await card.locator('h3').innerText();
 await card.getByRole('button',{name:/Request partnership/}).click();
 await expect(card).toContainText('pending');
 await page.goto('/login');
 await page.locator('.demo-accounts button').filter({hasText:organization}).click();
 await expect(page.getByRole('heading',{name:/Welcome back/})).toBeVisible();
 await page.goto('/partnerships');
 const request=page.locator('.partnership-list>.panel').filter({hasText:'Browser journey'}).first();
 await request.getByRole('button',{name:'Accept request'}).click();
 await expect(request).toContainText('accepted');
 await request.getByLabel('Cumulative delivered total (INR)').fill('60');
 await request.getByRole('button',{name:'Record delivery'}).click();
 await expect(request.locator('.partnership-values')).toContainText('60 INR');
 await page.reload();
 await expect(page.locator('.partnership-list>.panel').filter({hasText:'Browser journey'}).first()).toContainText('60 INR');
 await page.goto('/impact');
 await expect(page.getByRole('heading',{name:'Collective effort. Visible progress.'})).toBeVisible();
 expect(errors).toEqual([]);
});
